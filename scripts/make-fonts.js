// Generates src/theme/fonts.css: Geist Sans (variable) + Geist Mono (regular) embedded as base64.
// x.com is https, so file:// font URLs would be blocked; data: URIs are not.
const fs = require('fs');
const path = require('path');

const base = path.join(__dirname, '..', 'node_modules', 'geist', 'dist', 'fonts');
const b64 = (p) => fs.readFileSync(path.join(base, p)).toString('base64');

const weights = [[400, 'Regular'], [500, 'Medium'], [600, 'SemiBold']];
const sansFaces = weights.map(([w, name]) =>
  `@font-face { font-family: "Geist"; font-weight: ${w}; font-style: normal; font-display: block; src: url(data:font/woff2;base64,${b64(`geist-sans/Geist-${name}.woff2`)}) format("woff2"); }`).join('\n');

const css = `/* Generated by scripts/make-fonts.js: do not edit. Geist is licensed under the SIL OFL 1.1. */
${sansFaces}
@font-face { font-family: "Geist Mono"; font-weight: 400; font-style: normal; font-display: block; src: url(data:font/woff2;base64,${b64('geist-mono/GeistMono-Regular.woff2')}) format("woff2"); }
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'theme', 'fonts.css'), css);
console.log('fonts.css written,', Math.round(css.length / 1024), 'KB');
